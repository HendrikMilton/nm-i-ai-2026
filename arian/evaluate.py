"""
Local evaluation for the Astar Island autoresearch loop.

Computes a score (0-100) matching the real competition scoring formula
WITHOUT using any API queries. Uses synthetic ground truth generated by
running the simulator with known random parameters.

Usage:
    python evaluate.py              # single evaluation with default settings
    python evaluate.py --runs 200  # use 200 ground-truth runs for stability
    python evaluate.py --seeds 3   # evaluate on 3 synthetic maps

This is what the autoresearch agent calls after each iteration of simulator.py
to decide whether to keep or revert a change.
"""
import argparse
import time
import numpy as np

from simulator import (
    SimParams,
    run_simulation,
    monte_carlo_predict,
    apply_static_overrides,
    parse_initial_grid,
    is_static,
    OCEAN, MOUNTAIN, PLAINS, SETTLE, PORT, FOREST, RUIN, EMPTY,
)


# ---------------------------------------------------------------------------
# Synthetic map generator
# ---------------------------------------------------------------------------

def generate_synthetic_map(
    rng: np.random.Generator,
    width: int = 40,
    height: int = 40,
    n_settlements: int = 6,
) -> tuple[list[list[int]], list[dict]]:
    """
    Generate a plausible Norse island map matching the documented structure:
    - Ocean border
    - Interior plains
    - Mountain chains (random walk)
    - Forest patches
    - Initial settlements on land, spaced apart

    Returns (grid_list, settlements_data) matching the API initial_state format.
    """
    grid = np.full((height, width), PLAINS, dtype=np.int32)

    # Ocean border (1 cell thick)
    grid[0, :] = OCEAN
    grid[-1, :] = OCEAN
    grid[:, 0] = OCEAN
    grid[:, -1] = OCEAN

    # Random fjords cutting inland from edges
    n_fjords = rng.integers(2, 5)
    for _ in range(n_fjords):
        edge = rng.integers(4)
        if edge == 0:   x, y, dx, dy = rng.integers(2, width-2), 1, 0, 1
        elif edge == 1: x, y, dx, dy = rng.integers(2, width-2), height-2, 0, -1
        elif edge == 2: x, y, dx, dy = 1, rng.integers(2, height-2), 1, 0
        else:           x, y, dx, dy = width-2, rng.integers(2, height-2), -1, 0
        length = rng.integers(3, 10)
        for _ in range(length):
            if 0 < x < width-1 and 0 < y < height-1:
                grid[y, x] = OCEAN
                # Widen fjord slightly
                for side in [-1, 1]:
                    sx = x + (side if dx == 0 else 0)
                    sy = y + (side if dy == 0 else 0)
                    if 0 < sx < width-1 and 0 < sy < height-1:
                        if rng.random() < 0.4:
                            grid[sy, sx] = OCEAN
            x += dx
            y += dy

    # Mountain chains via random walk
    n_chains = rng.integers(1, 4)
    for _ in range(n_chains):
        x = int(rng.integers(5, width-5))
        y = int(rng.integers(5, height-5))
        length = rng.integers(5, 20)
        for _ in range(length):
            if 1 < x < width-2 and 1 < y < height-2 and grid[y, x] != OCEAN:
                grid[y, x] = MOUNTAIN
            dx = int(rng.integers(-1, 2))
            dy = int(rng.integers(-1, 2))
            x = max(1, min(width-2, x + dx))
            y = max(1, min(height-2, y + dy))

    # Forest patches
    n_patches = rng.integers(4, 10)
    for _ in range(n_patches):
        cx = int(rng.integers(3, width-3))
        cy = int(rng.integers(3, height-3))
        size = rng.integers(3, 8)
        for dy in range(-size, size+1):
            for dx in range(-size, size+1):
                nx, ny = cx+dx, cy+dy
                if 0 < nx < width-1 and 0 < ny < height-1:
                    if grid[ny, nx] == PLAINS and rng.random() < 0.5:
                        grid[ny, nx] = FOREST

    # Place settlements on non-ocean, non-mountain cells, spaced apart
    settlements = []
    land_ys, land_xs = np.where((grid != OCEAN) & (grid != MOUNTAIN))
    land_cells = list(zip(land_xs.tolist(), land_ys.tolist()))
    rng.shuffle(land_cells)

    min_spacing = 6
    for (sx, sy) in land_cells:
        if len(settlements) >= n_settlements:
            break
        # Check spacing from existing settlements
        too_close = any(
            abs(sx - s["x"]) + abs(sy - s["y"]) < min_spacing
            for s in settlements
        )
        if too_close:
            continue
        # Check if coastal (for port)
        is_coastal = any(
            grid[ny, nx] == OCEAN
            for ddx in [-1, 0, 1]
            for ddy in [-1, 0, 1]
            if 0 <= (nx := sx+ddx) < width and 0 <= (ny := sy+ddy) < height
        )
        grid[sy, sx] = PORT if is_coastal else SETTLE
        settlements.append({
            "x": sx, "y": sy,
            "has_port": is_coastal,
            "alive": True,
        })

    return grid.tolist(), settlements


# ---------------------------------------------------------------------------
# Scoring (matches real competition formula)
# ---------------------------------------------------------------------------

def entropy_weighted_kl(ground_truth: np.ndarray, prediction: np.ndarray) -> float:
    """
    Compute entropy-weighted KL divergence between ground truth and prediction.

    ground_truth: (H, W, 6) float array — probability per cell per class
    prediction:   (H, W, 6) float array — our predicted probabilities

    Returns the weighted_kl score (lower is better internally).
    Cells where ground truth entropy ≈ 0 (static cells) contribute ~nothing.
    """
    eps = 1e-10

    # Per-cell entropy of ground truth
    gt_safe = np.maximum(ground_truth, eps)
    entropy = -np.sum(gt_safe * np.log(gt_safe), axis=2)  # (H, W)

    # Per-cell KL divergence: KL(p || q) = sum p * log(p/q)
    pred_safe = np.maximum(prediction, eps)
    kl = np.sum(gt_safe * np.log(gt_safe / pred_safe), axis=2)  # (H, W)

    total_entropy = entropy.sum()
    if total_entropy < eps:
        return 0.0

    weighted_kl = (entropy * kl).sum() / total_entropy
    return float(weighted_kl)


def kl_to_score(weighted_kl: float) -> float:
    """Convert weighted KL divergence to 0-100 score (matches competition formula)."""
    return float(max(0.0, min(100.0, 100.0 * np.exp(-3.0 * weighted_kl))))


def compute_ground_truth(
    grid_list: list[list[int]],
    settlements_data: list[dict],
    true_params: SimParams,
    n_gt_runs: int,
    rng: np.random.Generator,
) -> np.ndarray:
    """
    Generate synthetic ground truth by running the simulator with known parameters
    many times. This mirrors what the competition organizers do.

    Returns (H, W, 6) probability array.
    """
    H, W = len(grid_list), len(grid_list[0])
    counts = np.zeros((H, W, 6), dtype=np.float32)

    for _ in range(n_gt_runs):
        run_rng = np.random.default_rng(int(rng.integers(2**31)))
        result = run_simulation(grid_list, settlements_data, true_params, run_rng)
        for cls in range(6):
            counts[:, :, cls] += (result == cls).astype(np.float32)

    total = np.maximum(counts.sum(axis=2, keepdims=True), 1.0)
    gt = counts / total
    # Small floor on ground truth too (organizers likely do this)
    gt = np.maximum(gt, 1e-6)
    gt = gt / gt.sum(axis=2, keepdims=True)
    return gt


# ---------------------------------------------------------------------------
# Main evaluation loop
# ---------------------------------------------------------------------------

def evaluate(
    n_maps: int = 3,
    n_gt_runs: int = 200,
    n_pred_runs: int = 100,
    param_samples: int = 10,
    master_seed: int = 0,
) -> float:
    """
    Evaluate the predictor on `n_maps` synthetic maps with random true parameters.

    For each map:
      1. Generate random true SimParams (hidden from predictor)
      2. Run simulator n_gt_runs times with true params → ground truth distribution
      3. Run monte_carlo_predict (does NOT know true params) → predicted distribution
      4. Compute entropy-weighted KL → score (0-100)

    Returns mean score across all maps (higher = better).
    """
    rng = np.random.default_rng(master_seed)
    scores = []

    for map_idx in range(n_maps):
        print(f"[Map {map_idx + 1}/{n_maps}]")

        # Generate synthetic map
        map_rng = np.random.default_rng(int(rng.integers(2**31)))
        grid_list, settlements_data = generate_synthetic_map(map_rng)
        print(f"  Map: {len(grid_list)}×{len(grid_list[0])}, {len(settlements_data)} settlements")

        # Sample random "true" hidden parameters (these are unknown to the predictor)
        true_params = SimParams(
            expansion_rate=float(rng.uniform(0.05, 0.60)),
            conflict_prob=float(rng.uniform(0.05, 0.50)),
            winter_severity=float(rng.uniform(0.10, 0.70)),
            trade_range=int(rng.integers(4, 13)),
            ruin_reclaim_rate=float(rng.uniform(0.10, 0.60)),
            forest_reclaim_rate=float(rng.uniform(0.02, 0.25)),
            longship_prob=float(rng.uniform(0.05, 0.40)),
            longship_range=int(rng.integers(5, 16)),
        )

        # Ground truth: run with known true params many times
        t0 = time.time()
        gt_rng = np.random.default_rng(int(rng.integers(2**31)))
        ground_truth = compute_ground_truth(
            grid_list, settlements_data, true_params, n_gt_runs, gt_rng
        )
        print(f"  Ground truth ({n_gt_runs} runs): {time.time()-t0:.1f}s")

        # Prediction: Monte Carlo over parameter space (no knowledge of true params)
        t0 = time.time()
        pred_seed = int(rng.integers(2**31))
        prediction = monte_carlo_predict(
            grid_list, settlements_data,
            n_runs=n_pred_runs,
            param_samples=param_samples,
            seed=pred_seed,
        )
        initial_grid = parse_initial_grid(grid_list)
        prediction = apply_static_overrides(prediction, initial_grid)
        print(f"  Prediction  ({n_pred_runs} runs): {time.time()-t0:.1f}s")

        # Score
        wkl = entropy_weighted_kl(ground_truth, prediction)
        score = kl_to_score(wkl)
        scores.append(score)
        print(f"  weighted_kl={wkl:.4f}  score={score:.1f}/100")

    mean_score = float(np.mean(scores))
    print(f"\nMean score: {mean_score:.2f}/100  (individual: {[f'{s:.1f}' for s in scores]})")
    return mean_score


def main():
    parser = argparse.ArgumentParser(
        description="Local evaluation — no API queries used"
    )
    parser.add_argument("--maps", type=int, default=3,
                        help="Number of synthetic maps to evaluate on (default: 3)")
    parser.add_argument("--gt-runs", type=int, default=200,
                        help="Ground truth simulation runs per map (default: 200)")
    parser.add_argument("--pred-runs", type=int, default=100,
                        help="Predictor Monte Carlo runs per map (default: 100)")
    parser.add_argument("--param-samples", type=int, default=10,
                        help="LHS parameter samples for predictor (default: 10)")
    parser.add_argument("--seed", type=int, default=42,
                        help="Master random seed (default: 42)")
    args = parser.parse_args()

    print(f"Evaluating: {args.maps} maps, {args.gt_runs} GT runs, {args.pred_runs} pred runs")
    print()

    score = evaluate(
        n_maps=args.maps,
        n_gt_runs=args.gt_runs,
        n_pred_runs=args.pred_runs,
        param_samples=args.param_samples,
        master_seed=args.seed,
    )
    # Print in format autoresearch agent can parse
    print(f"score: {score:.2f}")


if __name__ == "__main__":
    main()
